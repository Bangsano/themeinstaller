                echo -e "\n${BOLD}Pilihan tidak valid! Silahkan pilih (y) atau (n).${NC}"
                ;;
        esac
    done

    print_banner "TEMA PANEL BERHASIL DI-RESET" "$GREEN"
    sleep 3
    return 0
