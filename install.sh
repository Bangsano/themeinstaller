safe_apt_update() {
    local update_log update_status=0 key

    update_log=$(apt-get update --allow-releaseinfo-change -y 2>&1) || update_status=$?
    printf '%s\n' "$update_log"

    if grep -q 'NO_PUBKEY' <<< "$update_log"; then
        print_warning "Terdeteksi GPG Key yang hilang! Mencoba memperbaiki otomatis..."
        while read -r key; do
            [[ -n "$key" ]] && run_optional apt-key adv --keyserver keyserver.ubuntu.com --recv-keys "$key"
        done < <(grep -oE 'NO_PUBKEY [0-9A-F]+' <<< "$update_log" | awk '!seen[$2]++ {print $2}')
        apt-get update --allow-releaseinfo-change -y
        print_success "GPG Key berhasil dipulihkan."
    elif (( update_status != 0 )); then
        return "$update_status"
    fi
}

