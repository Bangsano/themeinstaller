}

ensure_composer() {
    if ! command -v composer >/dev/null 2>&1; then
        print_info "Composer belum terpasang. Menginstal Composer..."
        curl -fSL https://getcomposer.org/installer | php -- --install-dir=/usr/local/bin --filename=composer
    fi
}

install_composer_dependencies() {
    local attempt status
    local -a composer_args=(install --no-dev --optimize-autoloader --no-interaction)

    ensure_composer
    rm -rf /var/www/.cache
    mkdir -p /var/www/.cache
    chown -R www-data:www-data /var/www/.cache
    export COMPOSER_ALLOW_SUPERUSER=1
    export COMPOSER_PROCESS_TIMEOUT=2000
    run_optional composer clear-cache

    for ((attempt = 1; attempt <= 3; attempt++)); do
        print_info "Menjalankan Composer dengan prefer-dist (percobaan $attempt/3)..."
        if composer "${composer_args[@]}" --prefer-dist; then
            print_success "Composer install dengan prefer-dist berhasil."
            return 0
        else
            status=$?
            print_warning "Composer prefer-dist gagal pada percobaan $attempt/3 (exit code $status)."
        fi

        if (( attempt < 3 )); then
            sleep $((attempt * 2))
        fi
    done

    print_warning "Tiga percobaan prefer-dist gagal. Beralih ke prefer-source sebagai fallback..."
    if composer "${composer_args[@]}" --prefer-source; then
        print_success "Composer install dengan prefer-source berhasil."
        return 0
    else
        status=$?
        print_error "Composer install gagal dengan prefer-dist maupun prefer-source (exit code $status)."
        return "$status"
    fi
}

