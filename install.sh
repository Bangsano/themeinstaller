            return 1
        fi
        if ! neobrutalism_mark_snapshot_retired "$backup_dir"; then
            print_error "Panel telah dipulihkan, tetapi snapshot belum berhasil masuk masa retensi. State tetap dipertahankan untuk pemulihan ulang."
            return 1
        fi
        if ! rm -f -- "$NEOBRUTALISM_STATE_FILE" "$NEOBRUTALISM_PANEL_MARKER"; then
            print_error "Rollback selesai tetapi state installer gagal dibersihkan. Snapshot tetap dipertahankan: $backup_dir"
            return 1
        fi
        print_warning "Panel dikembalikan ke source sebelum NEOBRUTALISM. Snapshot disimpan selama ${NEOBRUTALISM_BACKUP_RETENTION_DAYS} hari: $backup_dir"
        return 1
    fi

    print_success "Tema '$TARGET_NAME' berhasil diinstall."
    print_info "Snapshot rollback panel dan database tersimpan di: $backup_dir"
    print_info "RESEND_KEY ditambahkan kosong bila belum ada dan mailer 'resend' didaftarkan. MAIL_MAILER dan alamat pengirim tidak diubah; konfigurasi domain/API key tetap perlu diisi sendiri."
    print_banner "INSTALASI TEMA SELESAI" "$GREEN"
    sleep 3
    return 0
}

neobrutalism_uninstall() {
    local backup_dir

    if ! backup_dir=$(neobrutalism_read_backup_state); then
        print_error "State/marker snapshot NEOBRUTALISM tidak valid atau backup tidak ditemukan. Reset generik dibatalkan untuk mencegah kehilangan data."
        return 1
    fi

    create_temp_dir || return 1
    print_info "Memulihkan source panel dari snapshot $backup_dir..."
    cd "$PANEL_DIR" || { print_error "Tidak dapat masuk ke direktori panel untuk pemulihan."; return 1; }
    if [[ ! -f "$backup_dir/panel_replacement_started" ]]; then
        if ! php artisan down; then
            print_error "Tidak dapat mengaktifkan maintenance mode. Source panel belum disentuh; snapshot dipertahankan."
            return 1
        fi
    fi
    if systemctl list-unit-files --type=service --no-legend | awk '{print $1}' | grep -qx 'pteroq.service'; then
        if ! systemctl stop pteroq; then
            print_error "Gagal menghentikan queue worker. Pemulihan dibatalkan agar source tidak diganti ketika worker masih berjalan."
            return 1
        fi
    fi

    if [[ -f "$backup_dir/database_migration_started" ]]; then
        print_warning "Terdeteksi instalasi yang terputus sebelum selesai; database akan dikembalikan ke snapshot pra-instalasi."
    fi
    if [[ -f "$backup_dir/panel_replacement_started" || -f "$backup_dir/installation_complete" ]]; then
        if ! neobrutalism_restore_panel_snapshot "$backup_dir" yes; then
            print_error "Pemulihan source gagal. State snapshot dipertahankan: $NEOBRUTALISM_STATE_FILE"
            return 1
        fi
    fi
    if [[ -f "$backup_dir/database_migration_started" ]] && ! neobrutalism_restore_database "$backup_dir"; then
        print_error "Pemulihan database gagal. Panel harus tetap dalam maintenance mode; backup: $backup_dir"
        return 1
    fi

    cd "$PANEL_DIR" || { print_error "Tidak dapat masuk ke direktori panel setelah pemulihan."; return 1; }
    run_optional php artisan optimize:clear
    if ! set_panel_permissions; then
        print_error "Source sudah dipulihkan, tetapi permission panel gagal diterapkan. Panel tetap dalam maintenance mode."
        return 1
    fi
    if ! neobrutalism_restart_php_fpm; then
        print_error "Source panel telah dipulihkan, tetapi PHP-FPM belum berhasil dimuat ulang. State dan backup dipertahankan."
        return 1
    fi
    if ! php artisan up; then
        print_error "Source panel telah dipulihkan, tetapi gagal keluar dari maintenance mode. State dan backup dipertahankan."
        return 1
    fi
    run_optional systemctl restart pteroq
    if [[ ! -f "$backup_dir/panel_replacement_started" && ! -f "$backup_dir/installation_complete" && ! -f "$backup_dir/database_migration_started" ]]; then
        if ! rm -f -- "$NEOBRUTALISM_STATE_FILE" "$NEOBRUTALISM_PANEL_MARKER"; then
            print_error "State installer gagal dibersihkan. Snapshot dipertahankan: $backup_dir"
            return 1
        fi
        rm -rf -- "$backup_dir"
        print_success "Percobaan instalasi dibersihkan; source panel original tidak pernah diganti."
        return 0
    fi
    if ! neobrutalism_mark_snapshot_retired "$backup_dir"; then
        print_error "Source sudah dipulihkan, tetapi snapshot belum berhasil masuk masa retensi. State tetap dipertahankan untuk pemulihan ulang."
        return 1
    fi
    if ! rm -f -- "$NEOBRUTALISM_STATE_FILE" "$NEOBRUTALISM_PANEL_MARKER"; then
        print_error "Source sudah dipulihkan, tetapi state installer gagal dibersihkan. Snapshot dipertahankan untuk pemulihan ulang."
        return 1
    fi
    print_success "Source panel sebelum NEOBRUTALISM berhasil dipulihkan."
    print_info "Database tidak di-restore pada reset normal agar data akun/server terbaru tidak hilang; migrasi tema yang bersifat tambahan tetap tersimpan."
    print_info "Jika MAIL_MAILER pernah diubah menjadi 'resend', kembalikan nilainya ke mailer yang tersedia pada panel original."
    print_info "Snapshot lengkap termasuk dump database dan storage pra-instalasi disimpan selama ${NEOBRUTALISM_BACKUP_RETENTION_DAYS} hari: $backup_dir"
    print_info "Snapshot yang melewati masa retensi dibersihkan pada eksekusi installer berikutnya."
}

theme_archive_extract_safe() {
    local archive="$1" destination="$2"
    if ! command -v python3 >/dev/null 2>&1; then
        print_info "Python 3 belum tersedia; memasang runtime untuk validasi arsip yang aman..."
        apt-get install -y python3 || return 1
    fi
    python3 - "$archive" "$destination" <<'PY_THEME_ARCHIVE'
import os, re, shutil, stat, sys, tarfile, zipfile
from pathlib import Path

archive, destination = sys.argv[1:3]
root = Path(destination)
root.mkdir(mode=0o700, parents=True, exist_ok=False)
max_entries = 50000
reserve_bytes = 128 * 1024 * 1024
entries = []
file_paths = set()
excluded = 0
metadata = 0

def safe_parts(raw_name):
    if not raw_name or "\x00" in raw_name or "\\" in raw_name:
        raise ValueError(f"Nama path arsip tidak valid: {raw_name!r}")
    name = raw_name
    while name.startswith("./"):
        name = name[2:]
    if name.startswith("/") or re.match(r"^[A-Za-z]:", name):
        raise ValueError(f"Path absolut tidak diizinkan: {raw_name!r}")
    name = name.rstrip("/")
    if not name:
        return (), True
    parts = tuple(name.split("/"))
    if any(part in ("", ".", "..") for part in parts):
        raise ValueError(f"Path traversal/komponen path tidak valid: {raw_name!r}")
    return parts, raw_name.endswith("/")

def payload_relative(parts):
    if not parts or parts[0] != "pterodactyl" or len(parts) == 1:
        return None
    relative = parts[1:]
    if relative == (".env",) or relative[0] == "storage":
        return ""
    if relative[0] == ".env":
        raise ValueError(".env tidak boleh dijadikan direktori di dalam arsip tema.")
    return "/".join(relative)

def add_entry(parts, is_dir, kind, size, mode, handle):
    global excluded, metadata
    if not parts or parts[0] != "pterodactyl":
        metadata += 1
        return
    if is_dir:
        return
    relative = payload_relative(parts)
    if relative == "":
        excluded += 1
        return
    if relative is None:
        metadata += 1
        return
    if kind not in (0, stat.S_IFREG):
        raise ValueError(f"Hanya file reguler yang diperbolehkan: {'/'.join(parts)}")
    if size < 0:
        raise ValueError(f"Ukuran file tidak valid: {'/'.join(parts)}")
    if relative in file_paths:
        raise ValueError(f"Path file duplikat dalam arsip: {relative}")
    file_paths.add(relative)
    entries.append((parts, relative, size, mode, handle))

try:
    if archive.lower().endswith(".zip"):
        with zipfile.ZipFile(archive) as zf:
            infos = zf.infolist()
            if len(infos) > max_entries:
                raise ValueError(f"Jumlah entri arsip melebihi batas {max_entries}.")
            for info in infos:
                parts, trailing_dir = safe_parts(info.filename)
                mode = (info.external_attr >> 16) & 0xFFFF
                kind = stat.S_IFMT(mode)
                is_dir = info.is_dir() or trailing_dir or kind == stat.S_IFDIR
                if kind not in (0, stat.S_IFREG, stat.S_IFDIR):
                    raise ValueError(f"Symlink/special file tidak diizinkan: {info.filename}")
                if (info.is_dir() or trailing_dir) and kind == stat.S_IFREG:
                    raise ValueError(f"Metadata tipe file ZIP tidak konsisten: {info.filename}")
                add_entry(parts, is_dir, kind, info.file_size, mode, info)
            if not entries:
                raise ValueError("Arsip tidak memiliki file panel yang dapat dipasang di bawah pterodactyl/.")
            for relative in file_paths:
                parts = relative.split("/")
                if any("/".join(parts[:index]) in file_paths for index in range(1, len(parts))):
                    raise ValueError(f"Satu path dipakai sebagai file sekaligus direktori: {relative}")
            total_size = sum(item[2] for item in entries)
            available = shutil.disk_usage(root).free
            if total_size > max(0, available - reserve_bytes):
                raise ValueError("Ukuran hasil ekstraksi melebihi ruang aman yang tersedia.")
            for parts, relative, size, mode, info in entries:
                target = root.joinpath(*parts)
                target.parent.mkdir(mode=0o755, parents=True, exist_ok=True)
                written = 0
                with zf.open(info, "r") as source, target.open("xb") as output:
                    while True:
                        chunk = source.read(1024 * 1024)
                        if not chunk:
                            break
                        written += len(chunk)
                        if written > size:
                            raise ValueError(f"Ukuran aktual file melebihi metadata: {relative}")
                        output.write(chunk)
                if written != size:
                    raise ValueError(f"Ukuran hasil ekstraksi tidak cocok: {relative}")
                os.chmod(target, 0o644 | (mode & 0o111))
    else:
        with tarfile.open(archive, "r:gz") as tf:
            members = tf.getmembers()
            if len(members) > max_entries:
                raise ValueError(f"Jumlah entri arsip melebihi batas {max_entries}.")
            for member in members:
                parts, trailing_dir = safe_parts(member.name)
                if member.isdir() or trailing_dir:
                    if not member.isdir():
                        raise ValueError(f"Metadata tipe direktori TAR tidak konsisten: {member.name}")
                    continue
                if not member.isfile():
                    raise ValueError(f"Symlink/hardlink/special file tidak diizinkan: {member.name}")
                add_entry(parts, False, stat.S_IFREG, member.size, member.mode, member)
            if not entries:
                raise ValueError("Arsip tidak memiliki file panel yang dapat dipasang di bawah pterodactyl/.")
            for relative in file_paths:
                parts = relative.split("/")
                if any("/".join(parts[:index]) in file_paths for index in range(1, len(parts))):
                    raise ValueError(f"Satu path dipakai sebagai file sekaligus direktori: {relative}")
            total_size = sum(item[2] for item in entries)
            available = shutil.disk_usage(root).free
            if total_size > max(0, available - reserve_bytes):
                raise ValueError("Ukuran hasil ekstraksi melebihi ruang aman yang tersedia.")
            for parts, relative, size, mode, member in entries:
                target = root.joinpath(*parts)
                target.parent.mkdir(mode=0o755, parents=True, exist_ok=True)
                source = tf.extractfile(member)
                if source is None:
                    raise ValueError(f"Konten file TAR tidak dapat dibaca: {relative}")
                written = 0
                with source, target.open("xb") as output:
                    while True:
                        chunk = source.read(1024 * 1024)
                        if not chunk:
                            break
                        written += len(chunk)
                        if written > size:
                            raise ValueError(f"Ukuran aktual file melebihi metadata: {relative}")
                        output.write(chunk)
                if written != size:
                    raise ValueError(f"Ukuran hasil ekstraksi tidak cocok: {relative}")
                os.chmod(target, 0o644 | (mode & 0o111))
    print(f"Berhasil memvalidasi {len(entries)} file panel; {excluded} entri .env/storage diabaikan; {metadata} entri metadata di luar pterodactyl/ tidak diekstrak.")
except Exception as exc:
    shutil.rmtree(root, ignore_errors=True)
    print(f"Validasi/ekstraksi arsip tema gagal: {exc}", file=sys.stderr)
    sys.exit(1)
PY_THEME_ARCHIVE
}

theme_overlay_apply() {
    local source_root="$1" source_file relative destination current staged part copied=0 i
    local -a path_parts=()

    [[ -d "$source_root" && ! -L "$source_root" ]] || {
        print_error "Direktori payload pterodactyl/ tidak ditemukan atau bukan direktori biasa."
        return 1
    }
    while IFS= read -r -d '' source_file; do
        [[ -f "$source_file" && ! -L "$source_file" ]] || {
            print_error "Payload tema berisi file yang tidak aman: $source_file"
            return 1
        }
        relative="${source_file#"$source_root"/}"
        [[ -n "$relative" && "$relative" != /* && "$relative" != ".env" && "$relative" != storage && "$relative" != storage/* && "$relative" != *"/../"* && "$relative" != ../* && "$relative" != */.. ]] || {
            print_error "Path payload tema tidak valid atau mencoba mengubah .env/storage: $relative"
            return 1
        }
        IFS='/' read -r -a path_parts <<< "$relative"
        current="$PANEL_DIR"
        for ((i = 0; i < ${#path_parts[@]} - 1; i++)); do
            part="${path_parts[$i]}"
            [[ -n "$part" && "$part" != . && "$part" != .. ]] || {
                print_error "Komponen direktori payload tidak valid: $relative"
                return 1
            }
            current+="/$part"
            if [[ -L "$current" ]]; then
                print_error "Direktori tujuan merupakan symlink; penyalinan dibatalkan: $current"
                return 1
            elif [[ -e "$current" && ! -d "$current" ]]; then
                print_error "Jalur tujuan seharusnya direktori, tetapi merupakan file: $current"
                return 1
            elif [[ ! -d "$current" ]]; then
                mkdir -m 0755 -- "$current" || return 1
            fi
        done
        destination="$PANEL_DIR/$relative"
        if [[ -L "$destination" || ( -e "$destination" && ! -f "$destination" ) ]]; then
            print_error "File tujuan merupakan symlink atau bukan file reguler: $destination"
            return 1
        fi
        staged=$(mktemp "${destination%/*}/.theme-installer.XXXXXX") || return 1
        if ! cp -p --no-preserve=ownership -- "$source_file" "$staged" || ! mv -fT -- "$staged" "$destination"; then
            rm -f -- "$staged"
            print_error "Gagal memasang file tema: $relative"
            return 1
        fi
        copied=$((copied + 1))
    done < <(find "$source_root" -type f -print0)

    if (( copied == 0 )); then
        print_error "Tidak ada file reguler yang dapat dipasang dari arsip tema."
        return 1
    fi
    print_success "$copied file tema berhasil ditambahkan/diperbarui tanpa menghapus file panel lainnya."
}

theme_detect_operations() {
    local source_root="$1" source_file relative
    THEME_BUILD_REQUIRED=no
    THEME_MIGRATE_REQUIRED=no
    while IFS= read -r -d '' source_file; do
        relative="${source_file#"$source_root"/}"
        case "$relative" in
            package.json|yarn.lock|webpack.mix.js|vite.config.*|postcss.config.*|tailwind.config.*|resources/*|*.tsx|*.jsx|*.scss|*.sass|*.less|*.vue)
                THEME_BUILD_REQUIRED=yes
                ;;
        esac
        case "$relative" in
            database/migrations/*.php)
                THEME_MIGRATE_REQUIRED=yes
                ;;
        esac
    done < <(find "$source_root" -type f -print0)
}

