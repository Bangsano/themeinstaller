    local THEME_ZIP_FILE=$(basename "$THEME_URL")

    print_info "[2/4] Mengekstrak file tema..."
    if [[ "$THEME_ZIP_FILE" == *.tar.gz ]]; then
        tar -xzf "$THEME_ZIP_FILE"
    else
        unzip -oq "$THEME_ZIP_FILE"
    fi

