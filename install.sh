validate_panel_installation() {
    local config_file="$PANEL_DIR/config/app.php"
    local version_line
    local panel_version

    if [[ ! -d "$PANEL_DIR" ]]; then
        print_error "Direktori Pterodactyl tidak ditemukan di $PANEL_DIR. Panel belum terpasang atau lokasinya berbeda."
        exit 1
    fi

    if [[ ! -f "$PANEL_DIR/artisan" || ! -f "$PANEL_DIR/composer.json" || ! -f "$config_file" ]]; then
        print_error "Folder $PANEL_DIR ditemukan, tetapi struktur instalasi Pterodactyl tidak lengkap atau tidak valid."
        exit 1
    fi

    version_line=$(grep -m1 -E "^[[:space:]]*'version'[[:space:]]*=>" "$config_file" || true)
    panel_version=$(sed -nE "s/.*=>[[:space:]]*['\"]([^'\"]+)['\"].*/\1/p" <<< "$version_line")

    if [[ "$panel_version" =~ ^v?2\. ]]; then
        print_error "Panel Pterodactyl v$panel_version terdeteksi. Skrip ini hanya kompatibel dengan Pterodactyl v1.x."
        exit 1
    fi

    if [[ ! "$panel_version" =~ ^v?1\.[0-9]+\.[0-9]+([.-][[:alnum:].+-]+)?$ ]]; then
        print_error "Versi panel tidak dapat dipastikan dari $config_file (terdeteksi: '${panel_version:-tidak diketahui}'). Skrip dihentikan untuk mencegah perubahan pada panel yang tidak didukung."
        exit 1
    fi

    print_success "Pterodactyl v$panel_version terdeteksi. Kompatibilitas versi dasar: v1.x."
}

require_disk_space() {
    local path available_kib
    local -a checked_paths=("$PANEL_DIR" "${TMPDIR:-/tmp}")

    for path in "${checked_paths[@]}"; do
        available_kib=$(df -PkP -- "$path" | awk 'NR == 2 {print $4}')
        if [[ ! "$available_kib" =~ ^[0-9]+$ ]]; then
            print_error "Tidak dapat memeriksa ruang penyimpanan pada $path."
            return 1
        fi

        if (( available_kib < MIN_FREE_SPACE_KIB )); then
            print_error "Ruang kosong pada filesystem $path kurang dari 2 GiB (tersedia: $((available_kib / 1024)) MiB). Minimal 2 GiB diperlukan."
            return 1
        fi
    done

    print_success "Ruang penyimpanan memenuhi batas minimum 2 GiB."
}

