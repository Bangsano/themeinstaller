            print_info "Mencoba menghapus database panel..."
            DB_NAME=$(grep "^DB_DATABASE=" /var/www/pterodactyl/.env | cut -d'=' -f2)
            DB_USER=$(grep "^DB_USERNAME=" /var/www/pterodactyl/.env | cut -d'=' -f2)
            DB_PASS=$(grep "^DB_PASSWORD=" /var/www/pterodactyl/.env | cut -d'=' -f2)
            if mysql -u root -e "DROP DATABASE IF EXISTS $DB_NAME; DROP USER IF EXISTS '$DB_USER'@'127.0.0.1';"; then
                print_success "Database cleaning selesai."
            else
                print_warning "Penghapusan database/user gagal. Lihat pesan MySQL di atas; file panel tetap akan diproses."
            fi
    else
            print_warning "File .env tidak ditemukan, melewati penghapusan database otomatis."
    fi

    print_info "Menghentikan layanan pterodactyl..."
    run_optional systemctl disable --now wings pteroq
    run_optional systemctl disable --now redis-server
    run_optional systemctl disable --now redis
    PHP_SERVICES=$(systemctl list-unit-files | grep -oE "php[0-9\.]+-fpm\.service" | tr "\n" " ")
    if [ ! -z "$PHP_SERVICES" ]; then
            run_optional systemctl disable --now $PHP_SERVICES
    fi
    run_optional systemctl stop nginx apache2

    print_info "Membersihkan Cronjob..."
    local current_crontab
    if current_crontab=$(crontab -l); then
        printf '%s\n' "$current_crontab" | grep -v "pterodactyl" | crontab -
    else
        print_warning "Crontab tidak dapat dibaca atau belum tersedia; tidak ada perubahan cron yang dilakukan."
    fi

    print_info "Menghapus file sistem Pterodactyl..."
    rm -rf /var/www/pterodactyl
    rm -rf /etc/pterodactyl
    rm -rf /var/lib/pterodactyl
    if [[ -e "$NEOBRUTALISM_STATE_FILE" || -L "$NEOBRUTALISM_STATE_FILE" ]]; then
        local neobrutalism_backup_dir
        if neobrutalism_backup_dir=$(neobrutalism_read_backup_state); then
            if neobrutalism_mark_snapshot_retired "$neobrutalism_backup_dir"; then
                print_info "Snapshot NEOBRUTALISM disimpan selama ${NEOBRUTALISM_BACKUP_RETENTION_DAYS} hari: $neobrutalism_backup_dir"
                if ! rm -f -- "$NEOBRUTALISM_STATE_FILE" "$NEOBRUTALISM_STATE_FILE".tmp.*; then
                    print_warning "State snapshot gagal dibersihkan; backup tetap dilindungi dari pembersihan otomatis."
                fi
            else
                print_warning "Snapshot tidak dapat ditandai untuk retensi; backup dan state dipertahankan: $neobrutalism_backup_dir"
            fi
        else
            print_warning "State snapshot NEOBRUTALISM tidak valid; backup dibiarkan utuh untuk pemeriksaan manual."
        fi
        rmdir "$(dirname "$NEOBRUTALISM_STATE_FILE")" 2>/dev/null || true
    fi
    rm -f /usr/local/bin/wings
    rm -f /usr/local/bin/composer
    rm -f /usr/local/bin/blueprint

    print_info "Menghapus konfigurasi service..."
    rm -f /etc/systemd/system/wings.service
    rm -f /etc/systemd/system/pteroq.service
    systemctl daemon-reload

    print_info "Menghapus konfigurasi webserver..."
    rm -f /etc/nginx/sites-enabled/pterodactyl.conf
    rm -f /etc/nginx/sites-available/pterodactyl.conf
    rm -f /etc/nginx/conf.d/pterodactyl.conf
    rm -f /etc/apache2/sites-enabled/pterodactyl.conf
    rm -f /etc/apache2/sites-available/pterodactyl.conf
    rm -f /etc/php/*/fpm/pool.d/www-pterodactyl.conf
    rm -f /etc/php-fpm.d/www-pterodactyl.conf
    if [ -f /etc/nginx/sites-available/default ] && [ ! -L /etc/nginx/sites-enabled/default ]; then
            run_optional ln -s /etc/nginx/sites-available/default /etc/nginx/sites-enabled/default
    fi

    print_info "Membersihkan sisa Docker..."
    if command -v docker >/dev/null 2>&1; then
        local docker_containers
        if docker_containers=$(docker ps -a -q); then
            if [[ -n "$docker_containers" ]]; then
                run_optional docker rm -f $docker_containers
            fi
        else
            print_warning "Gagal mengambil daftar container Docker; proses penghapusan container dilewati."
        fi
        run_optional docker system prune -af
    else
        print_warning "Docker tidak terdeteksi; pembersihan Docker dilewati."
    fi

    print_info "Merestart layanan sistem..."
    run_optional systemctl restart nginx
    run_optional systemctl restart apache2

    print_banner "UNINSTALL PANEL SELESAI" "$GREEN"
    sleep 3
    return 0
