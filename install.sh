print_logo() {
    local RESET=$'\033[0m' ICON_COLOR=$'\033[1;97m'
    local WHITE=$'\033[1;97m' CYAN=$'\033[1;96m' GREEN=$'\033[1;92m'
    local TERM_WIDTH=${COLUMNS:-$(tput cols 2>/dev/null || printf '80')}
    local LOGO_WIDTH=32 LEFT_PAD SIDE_LAYOUT line pad i j

    [[ "$TERM_WIDTH" =~ ^[0-9]+$ ]] || TERM_WIDTH=80

    local -a ART=(
        '                             ,;*='
        '                        ,;+#@@*'
        '                    ,-+#@@@@@*'
        '               .,  ,@@@@@@@@#.'
        '           .:-*%: .%@@@@@@@%,'
        '        :-*%@@@-  *@@@@@@@@,'
        '      ;*+=@@@@-  +@@@@@@@@:'
        '   ,=%@@%@@@@#. -@@@@@@@@;'
        '.:+##+-;:;@@@@%#@@@@@@@@-'
        '.:,       +@@@@@@@@@@@@='
        '          .%@@@@@@@@@@+'
        '           :%@@@@@@@@%,'
        '             ,:-+#%@@@@+:'
        '                  .:-=*%@*;.'
        '                        ,-+=,'
    )

    local -a INFO_TEXT=("PTERODACTYL" "AUTO INSTALLER THEME" "By Sano Official" "Telegram: @sanoofc")
    local -a INFO_COLOR=("$WHITE" "$CYAN" "$WHITE" "$GREEN")

    if (( TERM_WIDTH >= 72 )); then
        SIDE_LAYOUT=1
        LEFT_PAD=$(( (TERM_WIDTH - LOGO_WIDTH - 25) / 2 ))
    else
        SIDE_LAYOUT=0
        LEFT_PAD=$(( (TERM_WIDTH - LOGO_WIDTH) / 2 ))
    fi
    (( LEFT_PAD < 0 )) && LEFT_PAD=0

    printf '\n'
    for i in "${!ART[@]}"; do
        line=${ART[$i]}
        printf '%*s%b%s%b' "$LEFT_PAD" '' "$ICON_COLOR" "$line" "$RESET"

        if (( SIDE_LAYOUT && i >= 5 && i <= 8 )); then
            j=$((i - 5))
            pad=$((LOGO_WIDTH - ${#line} + 3))
            printf '%*s%b%s%b' "$pad" '' "${INFO_COLOR[$j]}" "${INFO_TEXT[$j]}" "$RESET"
        fi

        printf '\n'
    done

    if (( ! SIDE_LAYOUT )); then
        printf '\n'
        for i in "${!INFO_TEXT[@]}"; do
            pad=$(( (TERM_WIDTH - ${#INFO_TEXT[$i]}) / 2 ))
            (( pad < 0 )) && pad=0
            printf '%*s%b%s%b\n' "$pad" '' "${INFO_COLOR[$i]}" "${INFO_TEXT[$i]}" "$RESET"
        done
    fi

    printf '\n'
}

