    if ! printf '%s\n' "$backup_dir" > "$panel_marker_tmp" || ! chmod 0600 "$panel_marker_tmp" || ! chown root:root "$panel_marker_tmp" || ! mv -f -- "$panel_marker_tmp" "$NEOBRUTALISM_PANEL_MARKER"; then
