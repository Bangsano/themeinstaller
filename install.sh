install_yarn_dependencies() {
    local package
    local -a required_packages=("$@")
    local -a missing_packages=()

    for package in "${required_packages[@]}"; do
        if ! jq -e --arg package "$package" '(.dependencies[$package] // .devDependencies[$package]) != null' package.json >/dev/null; then
            missing_packages+=("$package")
        fi
    done

    if (( ${#missing_packages[@]} > 0 )); then
        yarn add "${missing_packages[@]}"
    fi
    yarn install
}

